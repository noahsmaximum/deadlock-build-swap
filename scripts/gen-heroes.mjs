// Regenerate heroes.js: node scripts/gen-heroes.mjs
// Names/IDs from leamare/deadlock-metadata; a hero is "playable" if deadlock.wiki/Heroes has its portrait.
import fs from 'fs';

const NAMES = 'https://raw.githubusercontent.com/leamare/deadlock-metadata/main/heroes/names.json';
const WIKI = 'https://deadlock.wiki/Heroes';
const UA = { 'User-Agent': 'Mozilla/5.0 (build-swap hero list generator)' };

const names = await (await fetch(NAMES, { headers: UA })).json();
const html = await (await fetch(WIKI, { headers: UA })).text();

const img = {};
// Full-size portrait is the srcset's 2x URL (absolute on the wiki CDN, or site-relative on older markup).
for (const [, url] of html.matchAll(/srcset="([^" ]+_vertical\.png) 2x"/g)) {
  const name = decodeURIComponent(url.split('/').pop().replace('_vertical.png', '')).replace(/_/g, ' ');
  img[name] ??= new URL(url, WIKI).href;
}
if (!Object.keys(img).length) throw new Error('No portraits found on the wiki page: markup changed, heroes.js left untouched');

const playable = [], other = {};
for (const [k, v] of Object.entries(names)) {
  if (!v.english) continue;
  if (img[v.english]) playable.push({ id: +k, name: v.english, img: img[v.english] });
  else other[k] = v.english;
}
playable.sort((a, b) => a.name.localeCompare(b.name));

const unmatched = Object.keys(img).filter(n => !playable.some(h => h.name === n));
if (unmatched.length) console.warn('Wiki portraits with no ID in names.json:', unmatched.join(', '));

const out = `// Generated by scripts/gen-heroes.mjs from leamare/deadlock-metadata heroes/names.json + deadlock.wiki/Heroes portraits.
// Playable heroes (have a wiki portrait), sorted by name.
export const HEROES = [
${playable.map(h => '  ' + JSON.stringify(h)).join(',\n')}
];

// Remaining named IDs (unreleased / test / NPC) so any build can still be labelled.
export const OTHER_NAMES = ${JSON.stringify(other)};
`;
fs.writeFileSync(new URL('../heroes.js', import.meta.url), out);
console.log(`${playable.length} playable heroes, ${Object.keys(other).length} other named IDs`);
